// Shape real encrypted QUIC datagrams. CDP's HTTP throttling does not constrain
// WebTransport, and replacing the SDK's probe would only test its selection math.
async function shapeMoq(target: URL) {
  const client = createSocket("udp4");
  const server = createSocket("udp4");
  const errors: string[] = [];
  for (const socket of [client, server]) {
    socket.on("error", (error) => errors.push(String(error)));
  }
  client.bind(0, "127.0.0.1");
  await once(client, "listening");
  server.connect(Number(target.port || 443), target.hostname);
  await once(server, "connect");
  let peer: RemoteInfo | undefined;
  let bitrate = 4_000_000;
  const changes = [{ at: Date.now(), bitrate }];
  let timer: ReturnType<typeof setTimeout> | undefined;
  let closed = false;
  let queued = 0;
  const packets: Buffer[] = [];
  const services: {
    at: number;
    bytes: number;
    bitrate: number;
    minimumMs: number;
    elapsedMs: number;
  }[] = [];
  const counters = { received: 0, sent: 0, dropped: 0, upstream: 0 };
  function sendNext() {
    if (closed || timer || !peer || packets.length === 0) return;
    const started = performance.now();
    const rate = bitrate;
    const minimumMs = (packets[0].length * 8000) / rate;
    const finish = () => {
      const elapsedMs = performance.now() - started;
      if (elapsedMs < minimumMs) {
        timer = setTimeout(finish, Math.ceil(minimumMs - elapsedMs));
        return;
      }
      timer = undefined;
      const packet = packets.shift()!;
      queued -= packet.length;
      counters.sent += packet.length;
      services.push({
        at: Date.now(),
        bytes: packet.length,
        bitrate: rate,
        minimumMs,
        elapsedMs,
      });
      client.send(packet, peer!.port, peer!.address);
      // A late timer delays the link; it never earns a catch-up burst.
      sendNext();
    };
    timer = setTimeout(finish, Math.ceil(minimumMs));
  }
  client.on("message", (packet, remote) => {
    if (closed) return;
    peer = remote;
    counters.upstream += packet.length;
    server.send(packet);
  });
  server.on("message", (packet) => {
    if (closed) return;
    counters.received += packet.length;
    // At most 200ms of backlog. A capacity drop must cause congestion feedback,
    // rather than accumulating an arbitrarily long playback delay in this proxy.
    if (queued + packet.length > Math.max(1500, (bitrate / 8) * 0.2)) {
      counters.dropped += packet.length;
      return;
    }
    packets.push(packet);
    queued += packet.length;
    sendNext();
  });
  const address = client.address();
  return {
    port: address.port,
    limit(bitsPerSecond: number) {
      clearTimeout(timer);
      timer = undefined;
      bitrate = bitsPerSecond;
      changes.push({ at: Date.now(), bitrate });
      while (queued > Math.max(1500, (bitrate / 8) * 0.2)) {
        const dropped = packets.pop()!;
        queued -= dropped.length;
        counters.dropped += dropped.length;
      }
      sendNext();
    },
    sample: () => ({ at: Date.now(), bitrate, queued, ...counters }),
    errors,
    services,
    changes,
    async close() {
      closed = true;
      clearTimeout(timer);
      client.close();
      server.close();
      await Promise.all([once(client, "close"), once(server, "close")]);
    },
  };
}

test("Enhanced RTMP Auto downshifts and recovers through a bandwidth-limited QUIC path", async ({
  page,
  request,
}, testInfo) => {
  test.skip(
    process.env.E2E_ERTMP !== "1" || !process.env.E2E_ERTMP_FIXTURES_DIR,
    "requires the real multires publisher fixtures generated by test/ertmp/generate.sh --abr",
  );
  test.setTimeout(180_000);
  const server = process.env.SERVER_URL;
  const did = process.env.ACCOUNT_DID;
  if (!server || !did) throw new Error("requires the local e2e harness");
  const discovery = new URL(
    "/xrpc/place.stream.playback.getPlaybackServer",
    server,
  );
  discovery.searchParams.set("stream", did);
  const response = await request.get(discovery.href);
  expect(response.ok()).toBe(true);
  const playback = await response.json();
  expect(playback.moq?.url).toBeTruthy();
  const target = new URL(playback.moq.url);
  expect(["127.0.0.1", "localhost"]).toContain(target.hostname);
  const shaper = await shapeMoq(target);
  const phases: unknown[] = [];
  const samples: ReturnType<typeof shaper.sample>[] = [];
  const sampler = setInterval(() => samples.push(shaper.sample()), 250);
  const errors: string[] = [];
  const subscriptions: { at: number; message: string }[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => {
    const text = message.text();
    if (/^subscribe (start|ok|close|error|update):/.test(text)) {
      subscriptions.push({ at: Date.now(), message: text });
    }
  });
  await page.route(
    "**/xrpc/place.stream.playback.getPlaybackServer?*",
    async (route) => {
      const actual = await route.fetch();
      const json = await actual.json();
      if (json.moq) {
        const url = new URL(json.moq.url);
        url.port = String(shaper.port);
        json.moq.url = url.href;
      }
      await route.fulfill({ response: actual, json });
    },
  );
  await page.addInitScript(observeAudioOutput);
  await page.addInitScript(() => {
    localStorage.setItem("player-transport", "webrtc");
    window.ertmpAbrFrames = [];
    window.ertmpAbrStats = [];
    window.ertmpAbrPictures = [];
    window.ertmpAbrDecoderEvents = [];
    let nextDecoder = 0;
    const copy = document.createElement("canvas");
    copy.width = 160;
    copy.height = 90;
    const context = copy.getContext("2d", { willReadFrequently: true })!;
    setInterval(() => {
      const stats = document.querySelector(
        '[role="dialog"][aria-label="Stats for Nerds"]',
      );
      if (stats?.textContent)
        window.ertmpAbrStats!.push({ at: Date.now(), text: stats.textContent });
      const surface = document.querySelector<HTMLCanvasElement>(
        '[data-playback-transport="moq"] canvas',
      );
      if (!surface?.width || !surface.height) return;
      context.drawImage(surface, 0, 0, 160, 90);
      const pixels = context.getImageData(0, 0, 160, 90).data;
      const [red, green, blue] = pixels.subarray(
        (160 + 1) * 4,
        (160 + 1) * 4 + 3,
      );
      let frame = 5381;
      for (const value of pixels) frame = ((frame * 33) ^ value) >>> 0;
      window.ertmpAbrPictures!.push({
        at: Date.now(),
        width: surface.width,
        height: surface.height,
        frame,
        color:
          red > green + 60 && red > blue + 60
            ? "red"
            : green > red + 60 && green > blue + 60
              ? "green"
              : blue > red + 60 && blue > green + 60
                ? "blue"
                : "unknown",
      });
    }, 250);
    const NativeDecoder = VideoDecoder;
    window.VideoDecoder = new Proxy(NativeDecoder, {
      construct(target, args, newTarget) {
        const options = args[0] as VideoDecoderInit;
        const id = nextDecoder++;
        window.ertmpAbrDecoderEvents!.push({
          at: Date.now(),
          decoder: id,
          event: "create",
        });
        let codec = "";
        const decoder = Reflect.construct(
          target,
          [
            {
              ...options,
              output(frame: VideoFrame) {
                window.ertmpAbrFrames!.push({
                  at: Date.now(),
                  decoder: id,
                  width: frame.codedWidth,
                  height: frame.codedHeight,
                  displayWidth: frame.displayWidth,
                  displayHeight: frame.displayHeight,
                  codec,
                  timestamp: frame.timestamp,
                });
                options.output(frame);
              },
              error(error: DOMException) {
                window.ertmpAbrDecoderEvents!.push({
                  at: Date.now(),
                  decoder: id,
                  event: "error",
                  error: String(error),
                });
                options.error(error);
              },
            },
          ],
          newTarget,
        ) as VideoDecoder;
        const configure = decoder.configure;
        decoder.configure = function (config) {
          codec = config.codec;
          window.ertmpAbrDecoderEvents!.push({
            at: Date.now(),
            decoder: id,
            event: "configure",
            codec,
          });
          return Reflect.apply(configure, this, [config]);
        };
        const decode = decoder.decode;
        let inputs = 0;
        decoder.decode = function (chunk) {
          if (inputs++ === 0 || chunk.type === "key")
            window.ertmpAbrDecoderEvents!.push({
              at: Date.now(),
              decoder: id,
              event: chunk.type,
              timestamp: chunk.timestamp,
            });
          return Reflect.apply(decode, this, [chunk]);
        };
        const close = decoder.close;
        decoder.close = function () {
          window.ertmpAbrDecoderEvents!.push({
            at: Date.now(),
            decoder: id,
            event: "close",
          });
          return Reflect.apply(close, this, []);
        };
        return decoder;
      },
    });
  });
  const player = page.locator("[data-playback-transport]");
  const canvas = player.locator("canvas");
  const stats = page.getByRole("dialog", { name: "Stats for Nerds" });
  async function picture() {
    return page.evaluate(
      () =>
        window.ertmpAbrPictures?.at(-1) ?? {
          at: 0,
          width: 0,
          height: 0,
          color: "unknown",
          frame: 0,
        },
    );
  }
  async function expectSteady(color: string, start: number, end: number) {
    const width = color === "green" ? 640 : 160;
    const height = color === "green" ? 360 : 90;
    const codec = color === "green" ? "av01." : "avc1.";
    const observation = await page.evaluate(
      ({ start, end, width, height, codec }) => ({
        pictures: window.ertmpAbrPictures!.filter(
          (picture) => picture.at >= start && picture.at <= end,
        ),
        frames: window.ertmpAbrFrames!.filter(
          (frame) =>
            frame.at >= start &&
            frame.at <= end &&
            frame.displayWidth === width &&
            frame.displayHeight === height &&
            frame.codec.startsWith(codec),
        ).length,
      }),
      { start, end, width, height, codec },
    );
    expect(observation.pictures.length).toBeGreaterThanOrEqual(8);
    expect(
      observation.pictures.every(
        (picture) =>
          picture.color === color &&
          picture.width === width &&
          picture.height === height,
      ),
    ).toBe(true);
    expect(
      new Set(observation.pictures.map((picture) => picture.frame)).size,
    ).toBeGreaterThan(4);
    expect(observation.frames).toBeGreaterThan(10);
  }
  async function expectPlaying(color: string) {
    await expect(player).toHaveAttribute("data-playback-transport", "moq");
    await expect.poll(async () => (await picture()).color).toBe(color);
    const before = await picture();
    await expect
      .poll(async () => (await picture()).frame)
      .not.toBe(before.frame);
    const width = color === "green" ? 640 : 160;
    const height = color === "green" ? 360 : 90;
    const codec = color === "green" ? "av01." : "avc1.";
    await expect
      .poll(() =>
        page.evaluate(
          ({ width, height, codec }) => {
            const frame = window.ertmpAbrFrames?.at(-1);
            return (
              frame?.displayWidth === width &&
              frame.displayHeight === height &&
              frame.codec.startsWith(codec)
            );
          },
          { width, height, codec },
        ),
      )
      .toBe(true);
    await expect
      .poll(() =>
        page.evaluate(
          () =>
            window.moqAudioAnalysers?.some((analyser) => {
              const pcm = new Float32Array(analyser.fftSize);
              analyser.getFloatTimeDomainData(pcm);
              return (
                analyser.context.state === "running" &&
                pcm.some((sample) => Math.abs(sample) > 0.0001)
              );
            }) ?? false,
        ),
      )
      .toBe(true);
    phases.push({
      ...(await picture()),
      frame: undefined,
      network: shaper.sample(),
      stats: await stats.innerText(),
    });
    await testInfo.attach(`abr-phase-${phases.length}`, {
      body: await page.screenshot(),
      contentType: "image/png",
    });
  }
  try {
    await page.goto(`/embed/${encodeURIComponent(did)}/`);
    await expect(canvas).toHaveCSS("opacity", "1");
    await player.hover();
    await player.locator('button[title="Unmute"]').click();
    await player.hover();
    await player.locator('button[title="Settings"]').click();
    await page
      .getByRole("menuitemcheckbox", { name: "Stats for Nerds" })
      .click();
    await page.keyboard.press("Escape");
    await expect(stats).toContainText("Video bitrate estimate");
    await expect(stats).toContainText("Bandwidth estimate");
    await expectPlaying("green");
    const restrictedBitrate = 1_000_000;
    shaper.limit(restrictedBitrate);
    const limited = shaper.sample();
    await expectPlaying("red");
    // Stay at the restricted rate through multiple GoPs, then restore capacity.
    const restricted = shaper.sample();
    await expect
      .poll(() => shaper.sample().sent - restricted.sent)
      .toBeGreaterThan((restrictedBitrate / 8) * 3);
    await expectPlaying("red");
    const end = shaper.sample();
    const maximumBytes =
      ((end.at - limited.at) * restrictedBitrate) / 8000 + 3000;
    expect(end.sent - limited.sent).toBeLessThanOrEqual(maximumBytes);
    await expectSteady("red", restricted.at, end.at);
    shaper.limit(4_000_000);
    await expectPlaying("green");
    const recovered = await picture();
    await expect
      .poll(async () => (await picture()).at)
      .toBeGreaterThan(recovered.at + 2_000);
    await expectSteady("green", recovered.at, (await picture()).at);
    expect(
      samples.some(
        (sample) => sample.bitrate === restrictedBitrate && sample.queued > 0,
      ),
    ).toBe(true);
    expect(shaper.errors).toEqual([]);
    expect(
      shaper.services.every(
        (service) => service.elapsedMs >= service.minimumMs,
      ),
    ).toBe(true);
    expect(errors).toEqual([]);
    expect(
      await page.evaluate(() =>
        window.ertmpAbrDecoderEvents!.filter(
          (event) => event.event === "error",
        ),
      ),
    ).toEqual([]);
  } finally {
    clearInterval(sampler);
    samples.push(shaper.sample());
    await shaper.close();
    const artifact = testInfo.outputPath("ertmp-abr.json");
    await writeFile(
      artifact,
      JSON.stringify({
        measurement: {
          rates: "bits per second",
          bytes:
            "UDP payload, including encrypted QUIC; excluding IP and UDP headers",
          shapedDirection: "server to browser",
          upstream: "unthrottled browser ACKs and control traffic",
          service:
            "each packet occupies length*8/rate seconds; late timers never earn catch-up credit",
          canvasSampleIntervalMs: 250,
        },
        phases,
        samples,
        packetServices: shaper.services,
        rateChanges: shaper.changes,
        errors,
        subscriptions,
        proxyErrors: shaper.errors,
        decoded: await page.evaluate(() => window.ertmpAbrFrames),
        painted: await page.evaluate(() => window.ertmpAbrPictures),
        decoderEvents: await page.evaluate(() => window.ertmpAbrDecoderEvents),
        stats: await page.evaluate(() => window.ertmpAbrStats),
      }),
    );
    await testInfo.attach("ertmp-abr", {
      path: artifact,
      contentType: "application/json",
    });
  }
});
