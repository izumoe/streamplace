func thumbnailVideoTrack(tb testing.TB, input []byte) (init, segment []byte, width, height int) {
	tb.Helper()
	events, err := segmentMuxlEvents(tb.Context(), input)
	require.NoError(tb, err)
	video, ok := primaryVideoTrack(catalogFromEvents(events), 0, "")
	require.True(tb, ok)
	id := strconv.FormatUint(uint64(video.TrackID()), 10)
	for _, event := range events {
		if len(event.TrackInits[id]) != 0 {
			init = event.TrackInits[id]
		}
	}
	segment = concatTrackAcrossSegments(events, id)
	require.NotEmpty(tb, init)
	require.NotEmpty(tb, segment)
	return init, segment, int(video.CodedWidth), int(video.CodedHeight)
}

func checkThumbnailImage(tb testing.TB, data []byte, format string, width, height int, border bool) {
	tb.Helper()
	decoded, gotFormat, err := image.Decode(bytes.NewReader(data))
	require.NoError(tb, err)
	require.Equal(tb, format, gotFormat)
	require.Equal(tb, min(width, 1280), decoded.Bounds().Dx())
	require.Equal(tb, min(height, 720), decoded.Bounds().Dy())
	if border {
		r, g, b, _ := decoded.At(2, 2).RGBA()
		require.Greater(tb, r, uint32(0x8000), "the fixture's red border must survive decoding and scaling")
		require.Greater(tb, r, 2*g)
		require.Greater(tb, r, 2*b)
	}
}

func checkThumbnailEntryPoints(t *testing.T, input []byte, border bool) {
	t.Helper()
	init, segment, width, height := thumbnailVideoTrack(t, input)
	for _, entry := range []string{"live", "vod"} {
		for _, format := range []string{"jpeg", "png"} {
			t.Run(entry+"/"+format, func(t *testing.T) {
				ctx, cancel := context.WithTimeout(t.Context(), 20*time.Second)
				defer cancel()
				var output bytes.Buffer
				if entry == "live" {
					require.NoError(t, Thumbnail(ctx, bytes.NewReader(input), &output, format))
				} else {
					require.NoError(t, ThumbnailFromSegment(ctx, init, segment, &output, format))
				}
				checkThumbnailImage(t, output.Bytes(), format, width, height, border)
				t.Logf("image_sha256=%x", sha256.Sum256(output.Bytes()))
				runtime.GC()
			})
		}
	}
}

func TestThumbnailCodecsAndFormats(t *testing.T) {
	require.NoError(t, muxl.Initialize())
	withNoGSTLeaks(t, func() {
		for _, fixture := range []string{"h264-opus-frag.mp4", "av1-aac-frag.mp4"} {
			t.Run(fixture, func(t *testing.T) {
				input, err := os.ReadFile(getFixture(fixture))
				require.NoError(t, err)
				checkThumbnailEntryPoints(t, input, false)
			})
		}
	})
}

func TestThumbnailDecodeErrors(t *testing.T) {
	require.NoError(t, muxl.Initialize())
	input, err := os.ReadFile(getFixture("h264-opus-frag.mp4"))
	require.NoError(t, err)
	init, segment, _, _ := thumbnailVideoTrack(t, input)
	video := append(bytes.Clone(init), segment...)
	withNoGSTLeaks(t, func() {
		for _, name := range []string{"empty", "malformed", "cancelled", "writer"} {
			t.Run(name, func(t *testing.T) {
				var logs logCapture
				previous := slog.Default()
				slog.SetDefault(slog.New(slog.NewTextHandler(&logs, nil)))
				t.Cleanup(func() { slog.SetDefault(previous) })
				verbosity := flag.Lookup("v").Value.String()
				require.NoError(t, flag.Set("v", "1"))
				t.Cleanup(func() { require.NoError(t, flag.Set("v", verbosity)) })
				ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
				defer cancel()
				data := video
				output := io.Discard
				switch name {
				case "empty":
					data = nil
				case "malformed":
					data = []byte("invalid MP4")
				case "cancelled":
					cancel()
				case "writer":
					r, w := io.Pipe()
					require.NoError(t, r.Close())
					defer w.Close()
					output = w
				}
				err := thumbnailFromMP4(ctx, data, output, "jpeg")
				require.Error(t, err)
				if name == "cancelled" {
					require.ErrorIs(t, err, context.Canceled)
				} else {
					require.NotErrorIs(t, err, context.DeadlineExceeded, "invalid input must fail rather than stall")
					require.Contains(t, logs.String(), "gstreamer error")
				}
				if name == "writer" {
					require.Contains(t, logs.String(), "error writing output")
				}
			})
		}
	})
}

func thumbnailMatrix(t testing.TB) string {
	t.Helper()
	dir := os.Getenv("STREAMPLACE_THUMBNAIL_FIXTURES_DIR")
	if dir == "" {
		t.Skip("set STREAMPLACE_THUMBNAIL_FIXTURES_DIR to fixtures generated by test/thumbnail/generate.sh")
	}
	return dir
}

func TestThumbnailResolutionMatrix(t *testing.T) {
	dir := thumbnailMatrix(t)
	require.NoError(t, muxl.Initialize())
	withNoGSTLeaks(t, func() {
		for _, codec := range []string{"h264", "av1"} {
			for _, height := range []int{360, 720, 1080, 2160} {
				name := codec + "-" + strconv.Itoa(height)
				t.Run(name, func(t *testing.T) {
					input, err := os.ReadFile(filepath.Join(dir, name+".mp4"))
					require.NoError(t, err)
					checkThumbnailEntryPoints(t, input, true)
				})
			}
		}
	})
}

func BenchmarkThumbnailDecode(b *testing.B) {
	dir := thumbnailMatrix(b)
	require.NoError(b, muxl.Initialize())
	for _, codec := range []string{"h264", "av1"} {
		for _, height := range []int{360, 720, 1080, 2160} {
			name := codec + "-" + strconv.Itoa(height)
			input, err := os.ReadFile(filepath.Join(dir, name+".mp4"))
			require.NoError(b, err)
			init, segment, width, h := thumbnailVideoTrack(b, input)
			for _, entry := range []string{"live", "vod"} {
				b.Run(name+"/"+entry, func(b *testing.B) {
					var output bytes.Buffer
					b.ReportAllocs()
					for b.Loop() {
						output.Reset()
						if entry == "live" {
							err = Thumbnail(b.Context(), bytes.NewReader(input), &output, "jpeg")
						} else {
							err = ThumbnailFromSegment(b.Context(), init, segment, &output, "jpeg")
						}
						if err != nil {
							b.Fatal(err)
						}
					}
					checkThumbnailImage(b, output.Bytes(), "jpeg", width, h, true)
				})
			}
		}
	}
}
